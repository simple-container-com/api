// EnvFileMode is the mode of the rendered env file on the machine. It holds every
// secret of the stack, so it is readable by its owner only (compose-on-vm.md §7.1).
const EnvFileMode = "0600"

// TextVolumeMode / TextVolumeSecretMode are the modes of a rendered `textVolumes`
// entry. A config file is world-readable; one whose content came from `${secret:…}` is
// not — mixed config-with-a-secret-inside is the common case, and defaulting it to 0644
// would quietly publish it to every user and every other container that bind-mounts the
// directory (§7.2).
const (
	TextVolumeMode       = "0644"
	TextVolumeSecretMode = "0600"
)

// RenderEnvFile renders the `env_file` every service of the stack-env reads.
//
// It is `env_file` and not compose `environment:` deliberately: values must not land in
// the generated YAML, which is read by eye during an incident and may end up pasted
// into a ticket (§7.1). The file is written through the command's Stdin, never through
// an argument or an environment variable — see compose_stack.go for why.
//
// `extra` carries the variables the compute context contributes at provisioning time
// (`${resource:…}` expansions from parent resources). It wins over `env` and loses to
// `secrets`, matching the precedence of every other target.
func RenderEnvFile(input *VmComposeInput, extra map[string]string) (string, error) {
	if input == nil || input.Deployment.StackConfig == nil {
		return "", errors.Errorf("input is nil")
	}
	cfg := input.Deployment.StackConfig

	values := lo.Assign(cfg.Env, extra, cfg.Secrets)
	keys := lo.Keys(values)
	sort.Strings(keys)

	var sb strings.Builder
	// No `GENERATED BY` header with a path hint here, unlike the compose file: this
	// file is parsed by docker as `KEY=value` lines, and while `#` comments are
	// tolerated, keeping it to exactly the data makes a corrupted file obvious.
	for _, k := range keys {
		if err := validateEnvKey(k); err != nil {
			return "", err
		}
		sb.WriteString(fmt.Sprintf("%s=%s\n", k, quoteEnvValue(values[k])))
	}
	return sb.String(), nil
}

// envKey is what docker's env-file parser accepts without surprises. Docker itself is
// laxer, but a key with a space or an `=` in it silently produces a variable the
// application will never find.
var envKey = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func validateEnvKey(k string) error {
	if !envKey.MatchString(k) {
		return errors.Errorf(
			"environment variable name %q cannot be used: it must match %s. Docker's env-file parser "+
				"would accept the line and produce a variable the application cannot read", k, envKey.String(),
		)
	}
	return nil
}

// quoteEnvValue makes a value survive docker's env-file parser.
//
// The parser is not a shell: it does not strip quotes, it splits on the first `=` and
// takes the rest of the LINE verbatim. So the only thing that genuinely breaks is a
// newline, and the fix is to escape it rather than to quote the value — quoting would
// make the quotes part of the value, which is the classic "why does my key have a
// leading double quote" bug.
func quoteEnvValue(v string) string {
	return strings.NewReplacer("\r\n", `\n`, "\n", `\n`, "\r", `\n`).Replace(v)
}

// TextVolumeFiles returns the `textVolumes` to write on the machine, with the mode each
// should get.
func TextVolumeFiles(input *VmComposeInput, stack, env string) []TextVolumeFile {
	if input == nil {
		return nil
	}
	return lo.Map(input.Deployment.TextVolumes, func(v k8s.SimpleTextVolume, _ int) TextVolumeFile {
		return TextVolumeFile{
			Path:      TextVolumePath(stack, env, v.Name),
			MountPath: v.MountPath,
			Content:   v.Content,
			// 0644, and the §7.2 "0600 if it came from ${secret:…}" rule is NOT applied
			// — not an oversight, a constraint in two parts. First, by the time a
			// textVolume reaches here the placeholder is resolved and its origin is
			// gone, so SC cannot tell. Second, and decisive: unlike the env file (which
			// the docker daemon reads as root) a textVolume is bind-mounted and read by
			// the CONTAINER's user, which SC does not know. A 0600 file owned by the ssh
			// user is unreadable to a container running as anyone else, and it fails as
			// the application not finding its config. Restoring the distinction needs
			// origin tracking in the resolver; TextVolumeSecretMode is kept for then.
			Mode: TextVolumeMode,
		}
	})
}

// TextVolumeFile is one rendered `textVolumes` entry, ready to be written.
type TextVolumeFile struct {
	Path      string `json:"path" yaml:"path"`
	MountPath string `json:"mountPath" yaml:"mountPath"`
	Content   string `json:"content" yaml:"content"`
	Mode      string `json:"mode" yaml:"mode"`
}
