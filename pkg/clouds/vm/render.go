// GeneratedHeader goes on top of every file SC writes onto the machine.
//
// The file WILL be read, and probably edited, by a human during an incident — so it has
// to say immediately that edits do not survive and where the source is
// (compose-on-vm.md §6 point 6). The doc writes this header in Russian; it is English
// here because `api` is a public repository whose artifacts are English throughout.
const GeneratedHeader = `# GENERATED BY SIMPLE CONTAINER — DO NOT EDIT.
# Rewritten on every deploy; local edits are lost.
# Source of truth: .sc/stacks/%s/client.yaml (stack %q, environment %q).
# Regenerate: sc deploy -s %s -e %s
`

// LogMaxSize / LogMaxFile bound the json-file log driver. Unbounded container logs
// filling the disk is the single most common way a long-lived VM dies, and it presents
// as the application failing rather than as a full disk.
const (
	LogMaxSize = "50m"
	LogMaxFile = "3"
)

// RenderOptions are the deploy-time facts the render needs and the conversion cannot
// know: which slot is being brought up, which image each service runs, and whether the
// ingress port is published on the host.
type RenderOptions struct {
	Stack string
	Env   string
	Slot  string
	// Version is the deploy version (CalVer `YYYY.MM.DD-<sha>` in CI). It is passed to
	// every container so that a running container can report what it is.
	Version string
	// Images maps a service name to the image reference to run. A service missing from
	// the map keeps whatever `image:` the conversion produced; a service with neither
	// is an error, because compose would try to build it on the machine.
	Images map[string]string
	// IngressHostPort publishes the ingress service's port on the host. Set before
	// Caddy exists (P5.2) and for `ingress.enable: false` (§8.4); 0 publishes nothing
	// and leaves the service reachable only over the docker network.
	IngressHostPort int
}

// RenderedCompose is what the deploy writes to the machine.
type RenderedCompose struct {
	// SlotProject / SlotFile is the blue-green slot: everything that can safely run in
	// two copies at once.
	SlotProject string
	SlotFile    string
	// DataProject / DataFile is the stateful project, which the flip never touches.
	// Both are empty when the stack has no stateful service (§9.1).
	DataProject string
	DataFile    string

	SlotServices []string
	DataServices []string
}

// Render produces the compose file(s) for one slot of one stack-env.
//
// It is a pure function on purpose — no Pulumi, no SSH, no clock. The generated file is
// the thing an operator will stare at when a deploy misbehaves, and being able to
// produce it in a unit test from a client.yaml is what keeps it reviewable.
func Render(input *VmComposeInput, opts RenderOptions) (*RenderedCompose, error) {
	if input == nil {
		return nil, errors.Errorf("input is nil")
	}
	if err := ValidateNames(opts.Stack, opts.Env); err != nil {
		return nil, err
	}
	if !lo.Contains(Slots, opts.Slot) {
		return nil, errors.Errorf("unknown slot %q; one of: %s", opts.Slot, strings.Join(Slots, ", "))
	}

	stateful := lo.SliceToMap(input.StatefulServices(), func(s string) (string, bool) { return s, true })
	res := &RenderedCompose{
		SlotProject: ProjectName(opts.Stack, opts.Env, opts.Slot),
	}

	slot := newComposeFile(res.SlotProject)
	data := newComposeFile(DataProjectName(opts.Stack, opts.Env))

	ingressName := ""
	if input.Deployment.IngressContainer != nil {
		ingressName = input.Deployment.IngressContainer.Name
	}

	for _, c := range input.Deployment.Containers {
		isData := stateful[c.Name]
		svc, err := input.renderService(c, opts, isData, c.Name == ingressName)
		if err != nil {
			return nil, err
		}
		if isData {
			data.Services[c.Name] = svc
			res.DataServices = append(res.DataServices, c.Name)
		} else {
			slot.Services[c.Name] = svc
			res.SlotServices = append(res.SlotServices, c.Name)
		}
	}
	if len(slot.Services) == 0 {
		return nil, errors.Errorf("stack has no services to run; check `runs` in client.yaml")
	}

	// Both projects attach to the same two external networks, which is what lets a
	// service in a slot resolve a stateful service in the data project by name.
	internal := InternalNetworkName(opts.Stack, opts.Env)
	for _, f := range []*composeFile{slot, data} {
		f.Networks = map[string]composeNetwork{
			networkKeyInternal: {External: true, Name: internal},
		}
		f.Volumes = map[string]composeVolume{}
	}
	if ingressName != "" && !stateful[ingressName] {
		slot.Networks[networkKeyIngress] = composeNetwork{External: true, Name: IngressNetwork}
	}
	for _, vol := range input.ExternalVolumes() {
		v := composeVolume{External: true, Name: ExternalVolumeName(opts.Stack, opts.Env, vol)}
		// Declared in whichever project mounts it; a volume mounted by both a slot
		// service and a data service is declared in both, which is fine because it is
		// external in each.
		if lo.SomeBy(input.MountsOfVolume(vol), func(m VmMount) bool { return !stateful[m.Service] }) {
			slot.Volumes[vol] = v
		}
		if lo.SomeBy(input.MountsOfVolume(vol), func(m VmMount) bool { return stateful[m.Service] }) {
			data.Volumes[vol] = v
		}
	}

	header := fmt.Sprintf(GeneratedHeader, opts.Stack, opts.Stack, opts.Env, opts.Stack, opts.Env)
	slotYaml, err := marshalCompose(header, slot)
	if err != nil {
		return nil, err
	}
	res.SlotFile = slotYaml

	if len(data.Services) > 0 {
		res.DataProject = data.Name
		dataYaml, err := marshalCompose(header, data)
		if err != nil {
			return nil, err
		}
		res.DataFile = dataYaml
	}
	return res, nil
}

func (i *VmComposeInput) renderService(c k8s.CloudRunContainer, opts RenderOptions, isData, isIngress bool) (composeService, error) {
	image := c.Image.Name
	if v, ok := opts.Images[c.Name]; ok && v != "" {
		image = v
	}
	if image == "" {
		return composeService{}, errors.Errorf(
			"no image for service %q: SC builds it from %q and the deploy must pass the resulting "+
				"reference; a compose file on the machine must never build", c.Name, c.Image.Context,
		)
	}

	containerName := SlotAlias(opts.Stack, opts.Env, c.Name, opts.Slot)
	if isData {
		// A stateful service has exactly one instance and outlives both slots, so its
		// name must not carry a slot.
		containerName = fmt.Sprintf("%s-%s", NamePrefix(opts.Stack, opts.Env), c.Name)
	}

	svc := composeService{
		Image:         image,
		ContainerName: containerName,
		Entrypoint:    c.Command,
		Command:       c.Args,
		// restart: always, not unless-stopped — the machine WILL reboot (kernel
		// updates, cloud maintenance) and the stack has to come back by itself
		// (compose-on-vm.md §6 point 3).
		Restart: "always",
		EnvFile: []string{EnvFilePath(opts.Stack, opts.Env)},
		Environment: lo.Assign(c.Env, map[string]string{
			EnvCloud:      EnvCloudVm,
			EnvSlot:       opts.Slot,
			EnvDeployment: opts.Version,
		}),
		Logging: &composeLogging{
			Driver:  "json-file",
			Options: map[string]string{"max-size": LogMaxSize, "max-file": LogMaxFile},
		},
		Networks: map[string]composeServiceNetwork{
			networkKeyInternal: {Aliases: []string{containerName}},
		},
	}
	if isData {
		// A stateful service belongs to no slot, so it carries no slot env either —
		// its bare compose name (which compose aliases automatically) is how services
		// in both slots reach it.
		svc.Environment = lo.OmitByKeys(svc.Environment, []string{EnvSlot})
	}
	if isIngress && !isData {
		// Only the ingress container joins the shared network, so that two stacks on
		// one machine cannot resolve each other's `mongo` (§6 point 1, §11 rule 2).
		svc.Networks[networkKeyIngress] = composeServiceNetwork{Aliases: []string{containerName}}
		if opts.IngressHostPort > 0 {
			svc.Ports = []string{fmt.Sprintf("%d:%d", opts.IngressHostPort, lo.FromPtr(c.MainPort))}
		}
	}
	if deploy := toComposeDeploy(c.Resources); deploy != nil {
		svc.Deploy = deploy
	}
	if hc, ok := i.HealthChecks[c.Name]; ok {
		svc.HealthCheck = &composeHealthCheck{
			Test:        hc.Test,
			Interval:    hc.Interval,
			Timeout:     hc.Timeout,
			StartPeriod: hc.StartPeriod,
			Retries:     hc.Retries,
		}
	}
	for _, dep := range i.DependsOn[c.Name] {
		if svc.DependsOn == nil {
			svc.DependsOn = map[string]composeDependsOn{}
		}
		svc.DependsOn[dep.Service] = composeDependsOn{Condition: lo.If(dep.Condition == "", "service_started").Else(dep.Condition)}
	}
	for _, m := range i.MountsOf(c.Name) {
		switch m.Type {
		case MountTypeVolume:
			svc.Volumes = append(svc.Volumes, mountString(m.Name, m.MountPath, m.ReadOnly))
		case MountTypeTmpfs:
			entry := m.MountPath
			if m.Size != "" {
				entry = fmt.Sprintf("%s:size=%s", m.MountPath, m.Size)
			}
			svc.Tmpfs = append(svc.Tmpfs, entry)
		}
	}
	for _, tv := range i.Deployment.TextVolumes {
		svc.Volumes = append(svc.Volumes, mountString(TextVolumePath(opts.Stack, opts.Env, tv.Name), tv.MountPath, true))
	}
	return svc, nil
}

func mountString(source, target string, readOnly bool) string {
	return fmt.Sprintf("%s:%s%s", source, target, lo.If(readOnly, ":ro").Else(""))
}

// toComposeDeploy converts the Kubernetes-shaped resources the shared converter
// produced into compose's units. Both numbers mean the same thing — a cgroup limit —
// but the spellings differ: k8s says `250m` CPU and `512Mi` memory, compose says
// `0.25` and `512m`. Rendering a k8s string into compose yields either a parse error
// or, worse, a limit 1024× off.
func toComposeDeploy(r *k8s.Resources) *composeDeploy {
	if r == nil {
		return nil
	}
	limits := toComposeResources(r.Limits)
	reservations := toComposeResources(r.Requests)
	if limits == nil && reservations == nil {
		return nil
	}
	return &composeDeploy{Resources: composeResourcesBlock{Limits: limits, Reservations: reservations}}
}

func toComposeResources(in map[string]string) *composeResources {
	if len(in) == 0 {
		return nil
	}
	res := &composeResources{}
	if cpu, ok := in["cpu"]; ok {
		res.CPUs = toComposeCPUs(cpu)
	}
	if mem, ok := in["memory"]; ok {
		res.Memory = toComposeMemory(mem)
	}
	if res.CPUs == "" && res.Memory == "" {
		return nil
	}
	return res
}

// toComposeCPUs turns millicores ("250m", "2000m") into compose's fractional cores
// ("0.25", "2"). A value without the `m` suffix is already in cores and passes through.
func toComposeCPUs(in string) string {
	if in == "" {
		return ""
	}
	if !strings.HasSuffix(in, "m") {
		return in
	}
	milli, err := strconv.ParseInt(strings.TrimSuffix(in, "m"), 10, 64)
	if err != nil {
		return ""
	}
	return strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.3f", float64(milli)/1000), "0"), ".")
}

// toComposeMemory turns a Kubernetes quantity ("512Mi", "4Gi") into compose's byte
// suffix ("512m", "4g"). Both are 1024-based, so only the suffix changes. A plain
// number is bytes in both and passes through.
func toComposeMemory(in string) string {
	for k8sSuffix, composeSuffix := range map[string]string{"Ki": "k", "Mi": "m", "Gi": "g", "Ti": "t"} {
		if strings.HasSuffix(in, k8sSuffix) {
			return strings.TrimSuffix(in, k8sSuffix) + composeSuffix
		}
	}
	if in == "0" {
		return ""
	}
	return in
}

func marshalCompose(header string, f *composeFile) (string, error) {
	var sb strings.Builder
	sb.WriteString(header)
	enc := yaml.NewEncoder(&sb)
	enc.SetIndent(2)
	if err := enc.Encode(f); err != nil {
		return "", errors.Wrapf(err, "failed to render compose file for project %q", f.Name)
	}
	if err := enc.Close(); err != nil {
		return "", errors.Wrapf(err, "failed to render compose file for project %q", f.Name)
	}
	return sb.String(), nil
}

// The network keys inside the generated file. They are local names; the real docker
// network names come from the `name:` of the external declaration.
const (
	networkKeyInternal = "internal"
	networkKeyIngress  = "ingress"
)

func newComposeFile(name string) *composeFile {
	return &composeFile{Name: name, Services: map[string]composeService{}}
}

// The compose subset SC generates. It is a typed subset rather than free text so that
// the renderer cannot emit syntactically valid nonsense, and a map rather than a slice
// so that yaml.v3 sorts the keys and the file is byte-stable across deploys.
type (
	composeFile struct {
		Name     string                    `yaml:"name"`
		Services map[string]composeService `yaml:"services"`
		Volumes  map[string]composeVolume  `yaml:"volumes,omitempty"`
		Networks map[string]composeNetwork `yaml:"networks,omitempty"`
	}

	composeService struct {
		Image         string                           `yaml:"image"`
		ContainerName string                           `yaml:"container_name,omitempty"`
		Entrypoint    []string                         `yaml:"entrypoint,omitempty"`
		Command       []string                         `yaml:"command,omitempty"`
		Restart       string                           `yaml:"restart,omitempty"`
		EnvFile       []string                         `yaml:"env_file,omitempty"`
		Environment   map[string]string                `yaml:"environment,omitempty"`
		Ports         []string                         `yaml:"ports,omitempty"`
		Volumes       []string                         `yaml:"volumes,omitempty"`
		Tmpfs         []string                         `yaml:"tmpfs,omitempty"`
		Networks      map[string]composeServiceNetwork `yaml:"networks,omitempty"`
		DependsOn     map[string]composeDependsOn      `yaml:"depends_on,omitempty"`
		HealthCheck   *composeHealthCheck              `yaml:"healthcheck,omitempty"`
		Deploy        *composeDeploy                   `yaml:"deploy,omitempty"`
		Logging       *composeLogging                  `yaml:"logging,omitempty"`
	}

	composeServiceNetwork struct {
		Aliases []string `yaml:"aliases,omitempty"`
	}

	composeDependsOn struct {
		Condition string `yaml:"condition"`
	}

	composeHealthCheck struct {
		Test        []string `yaml:"test"`
		Interval    string   `yaml:"interval,omitempty"`
		Timeout     string   `yaml:"timeout,omitempty"`
		StartPeriod string   `yaml:"start_period,omitempty"`
		Retries     *int     `yaml:"retries,omitempty"`
	}

	composeDeploy struct {
		Resources composeResourcesBlock `yaml:"resources"`
	}

	composeResourcesBlock struct {
		Limits       *composeResources `yaml:"limits,omitempty"`
		Reservations *composeResources `yaml:"reservations,omitempty"`
	}

	composeResources struct {
		CPUs   string `yaml:"cpus,omitempty"`
		Memory string `yaml:"memory,omitempty"`
	}

	composeLogging struct {
		Driver  string            `yaml:"driver"`
		Options map[string]string `yaml:"options,omitempty"`
	}

	composeVolume struct {
		External bool   `yaml:"external"`
		Name     string `yaml:"name"`
	}

	composeNetwork struct {
		External bool   `yaml:"external"`
		Name     string `yaml:"name"`
	}
)
