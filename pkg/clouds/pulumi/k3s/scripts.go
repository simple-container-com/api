const (
	// ServerUnit and AgentUnit are the systemd units the installer writes. Which one
	// it writes is decided by the FIRST positional argument it is given: `agent`
	// makes it `k3s-agent`, anything else `k3s`. That is also why an agent must not
	// be handed the server's flags — see AgentArgs.
	ServerUnit = "k3s"
	AgentUnit  = "k3s-agent"

	// ServerTokenPath is the join secret k3s writes on a server once it is up. Every
	// other node — agent or joining server — authenticates to the cluster with it.
	//
	// Read off the first server rather than generated by SC and passed in. Both work
	// for a cluster SC creates; only this one works for the cluster SC finds, which
	// is the normal case on byo hosts and after any out-of-band repair: a machine
	// that already has a k3s datastore keeps its own token, and a token SC invented
	// would be rejected by it with an authentication error on every join.
	ServerTokenPath = "/var/lib/rancher/k3s/server/node-token"

	// InstallerPath is where the install script is downloaded before it is run.
	// Downloaded and then executed, rather than piped into a shell: a truncated
	// transfer piped into `sh` executes the prefix that arrived, and the prefix of
	// this installer is the part that stops the running service.
	InstallerPath = "/tmp/sc-k3s-install.sh"

	// KubeconfigPath is where k3s writes the admin kubeconfig. Mode 0600, root-owned.
	KubeconfigPath = "/etc/rancher/k3s/k3s.yaml"

	// LocalServerURL is the `server:` URL k3s puts in the kubeconfig it writes. It is
	// correct on the node and useless anywhere else, which is what the rewrite below
	// is for.
	LocalServerURL = "https://127.0.0.1:6443"

	// nodeReadyAttempts × nodeReadyInterval = 300s. A single-node k3s reaches Ready in
	// well under a minute on a warm image; the slack is for a first boot that is also
	// pulling the packaged component images.
	nodeReadyAttempts = 60
	nodeReadyInterval = 5
)

// ArgsMarkerPath records the arguments SC installed a unit with, on the machine.
//
// It exists because the version alone is not enough to decide whether an install
// can be skipped. The remote half of this path has to be idempotent — a
// re-provision must not restart a working API server — but a guard that only
// compares versions would also skip an install whose `--tls-san` or `--disable`
// set had changed, and the operator would be looking at a cluster that does not
// match its own config with every layer reporting success. Comparing the full
// argument string makes "nothing to do" and "reconfigure" distinguishable
// remotely, which is the only place the question can be answered.
//
// Per unit, so a machine's marker says which thing it is: a host that was an agent
// and is now a server has a `k3s.args` to write and a stale `k3s-agent.args` that
// says nothing about it, rather than one file whose meaning changed underneath the
// comparison.
func ArgsMarkerPath(unit string) string {
	return vm.StateDir + "/" + unit + ".args"
}

// JoinSpec is how one node attaches to the cluster.
//
// The three shapes are the whole topology story, and they are mutually exclusive:
// the lone server of a single-server cluster (zero value), the first server of an
// embedded-etcd one (ClusterInit), and everything that joins an existing cluster
// (ServerURL — every agent, and every server after the first).
type JoinSpec struct {
	// ServerURL is the API server a node registers with: `https://<first server>:6443`.
	// Empty on the first server, which has nothing to register with.
	ServerURL string

	// ClusterInit asks k3s for an embedded-etcd datastore instead of sqlite, and is
	// set on the FIRST server of a multi-server cluster only.
	//
	// Not a function of "is this host 0": a single-server cluster deliberately does
	// not get it, because etcd on one node is a strictly worse sqlite — same single
	// point of failure, plus a quorum to lose. Raising `servers` from 1 later changes
	// this flag and so the args marker, which re-runs the install; k3s does migrate
	// sqlite to etcd on that restart, but it is a datastore conversion on a live
	// control plane and not something to do on a whim.
	ClusterInit bool

	// NodeIP is the address this node advertises to the rest of the cluster, and
	// becomes `--node-ip`. Empty on a single-node cluster, where there is no rest of
	// the cluster and k3s's own default is harmless.
	//
	// Set on every node of a multi-node cluster, because k3s's default is to use the
	// address of the default-route interface. On a cloud VM reached through a
	// floating/NAT IP that is already the internal address; on a single-NIC VPS it is
	// the PUBLIC one, and then etcd peer traffic and flannel's unencrypted VXLAN
	// overlay cross the public internet. Config-tier validation refuses a multi-node
	// pool whose private addresses are unknown (vm.VmHost.PrivateAddress), so by the
	// time this is empty on a multi-node cluster something upstream is wrong.
	//
	// It belongs in the args vector — and therefore in the args marker — on purpose:
	// a node whose advertised address changed must be reinstalled, not left
	// advertising a stale one.
	NodeIP string
}

// ServerArgs is the full argument vector SC installs a k3s server with, starting
// with the `server` subcommand. Rendered as one string because that is both what the
// installer takes and what ArgsMarkerPath compares.
//
// The join token is NOT here, deliberately: it would land in the marker file on the
// machine and in the Pulumi checkpoint as part of this string, and it would make the
// marker compare unequal on a cluster whose token was rotated — reinstalling a
// healthy control plane for a value the comparison has no business knowing. It
// travels as K3S_TOKEN instead (InstallScript).
func ServerArgs(cfg *k3s.K3sClusterConfig, sans []string, disable []string, join JoinSpec) string {
	args := []string{"server"}
	if join.ClusterInit {
		args = append(args, "--cluster-init")
	}
	if join.ServerURL != "" {
		args = append(args, "--server", join.ServerURL)
	}
	if join.NodeIP != "" {
		// Both flags, and both to the same value. `--node-ip` is what the node
		// advertises and what flannel and the kubelet bind to; without
		// `--advertise-address` the API server would still advertise its
		// default-route address to peers, which is the value this exists to avoid.
		args = append(args, "--node-ip", join.NodeIP, "--advertise-address", join.NodeIP)
	}
	for _, san := range sans {
		args = append(args, "--tls-san", san)
	}
	for _, c := range disable {
		args = append(args, "--disable", c)
	}
	args = append(args, cfg.ExtraServerArgs...)
	return strings.Join(args, " ")
}

// AgentArgs is the argument vector for a worker node.
//
// Short by design, and short in a load-bearing way: `--tls-san`, `--disable` and
// `extraServerArgs` are server-only flags. k3s's agent does not merely ignore them —
// it exits with an unknown-flag error, and the installer that forwarded them reports
// a service that will not start.
//
// `--node-ip` is NOT in that category: the agent accepts it, and an agent is where
// it matters most, since the kubelet and flannel both bind to the advertised
// address. `--advertise-address` is server-only and so is absent here.
func AgentArgs(join JoinSpec) string {
	args := []string{"agent", "--server", join.ServerURL}
	if join.NodeIP != "" {
		args = append(args, "--node-ip", join.NodeIP)
	}
	return strings.Join(args, " ")
}

// UnitFor is the systemd unit the installer will write for a role.
func UnitFor(role vm.HostRole) string {
	return lo.If(role == vm.RoleK3sAgent, AgentUnit).Else(ServerUnit)
}

// InstallScript is the remote half of standing up the control plane.
//
// Everything it does is conditional on the machine not already being in the wanted
// state, and the condition is checked on the machine: Pulumi's own Triggers decide
// whether the command RUNS, this decides whether running it changes anything. Both
// are needed — without Triggers a changed script never runs at all, and without the
// marker a re-run with an unchanged config would restart the API server of a live
// cluster for nothing.
func InstallScript(version, installURL, nodeArgs, unit, token string) string {
	marker := ArgsMarkerPath(unit)
	// The token rides the environment, never the argument vector (see ServerArgs).
	// The installer writes it 0600 into the unit's env file; `sudo env` is used for
	// the same reason INSTALL_K3S_VERSION is — it is the one form that survives
	// sudo's env_reset.
	tokenEnv := ""
	if token != "" {
		tokenEnv = fmt.Sprintf(` K3S_TOKEN=%q`, token)
	}
	return strings.Join([]string{
		`set -eu`,
		fmt.Sprintf(`WANT_VERSION=%q`, version),
		fmt.Sprintf(`WANT_ARGS=%q`, nodeArgs),
		fmt.Sprintf(`UNIT=%q`, unit),
		// The skip condition, spelled out: the service is running, the binary is the
		// wanted release, and the arguments on disk are the ones this config asks
		// for. Anything else falls through to a (re)install.
		fmt.Sprintf(`if sudo systemctl is-active --quiet "$UNIT" && `+
			`sudo k3s --version 2>/dev/null | grep -qF "$WANT_VERSION" && `+
			`[ -f %[1]s ] && [ "$(sudo cat %[1]s)" = "$WANT_ARGS" ]; then`, marker),
		`  echo "k3s $WANT_VERSION already running as $UNIT with the requested configuration"`,
		`  exit 0`,
		`fi`,
		fmt.Sprintf(`curl -fsSL %q -o %s`, installURL, InstallerPath),
		// `sudo env VAR=…` rather than `VAR=… sudo` or a pipe into `sudo sh`: the
		// first form is the only one that reliably survives sudo's env_reset, and
		// INSTALL_K3S_VERSION not arriving means the installer quietly takes the
		// latest release instead of the pinned one.
		//
		// $WANT_ARGS is deliberately unquoted: it is an argument VECTOR and the
		// installer forwards it to the service unit word by word. SC's own elements
		// are validated bare tokens (Validate refuses a SAN or a component name that
		// is anything else); `extraServerArgs` is word-split on spaces, which is the
		// documented behaviour of a pass-through field and the reason each entry
		// should be one flag.
		fmt.Sprintf(`sudo env INSTALL_K3S_VERSION="$WANT_VERSION"%s sh %s $WANT_ARGS`, tokenEnv, InstallerPath),
		fmt.Sprintf(`rm -f %s`, InstallerPath),
		// The installer does NOT guarantee a running service, and this is the line
		// that cost a provision: get.k3s.io diffs the unit and env files it would
		// write against what is on disk and, when they match, enables the unit and
		// prints
		//
		//	[INFO]  No change detected so skipping service start
		//
		// then exits 0. Its idempotence is unit-file-shaped, not service-shaped — so
		// against a machine whose k3s was stopped, killed or k3s-killall'd with an
		// otherwise correct config, the installer repairs nothing and reports
		// success, and the readiness gate 300 s later is the first thing that says
		// so. `enable --now` is the repair: a no-op on a running unit, a start on a
		// stopped one, and it cannot mask a genuine failure because `set -e` takes
		// the script down before the args marker below is written.
		//
		// Reaching this line at all means the skip condition above was false, i.e.
		// something really is wrong — on a first install the installer has already
		// started k3s and this is the no-op case.
		//
		// Live-caught 2026-10-18 on the RU smoke stand: the install re-ran (the
		// per-run trigger worked), printed the line above, wrote the marker, exited
		// 0 — and k3s stayed down, with nothing in its journal between the stop two
		// hours earlier and the failed gate.
		`sudo systemctl enable --now "$UNIT"`,
		// Written only after a successful install, so a failed one does not leave a
		// marker claiming the machine is configured.
		fmt.Sprintf(`printf '%%s' "$WANT_ARGS" | sudo tee %s >/dev/null`, marker),
		`echo "installed k3s $WANT_VERSION as $UNIT"`,
	}, "\n")
}

// UninstallScript removes k3s from a machine, and is what a `remote.Command`'s
// Delete runs when the resource goes away.
//
// Without it a destroyed cluster leaves k3s running on every machine. On one host
// that is a nuisance; on a fleet it is N nodes still serving, still holding ports 80
// and 443 against a compose stack that may be deployed there next, and — for the
// agents — still trying to register with a control plane that no longer answers.
//
// The installer writes the uninstaller, so its presence is the only honest test of
// whether k3s was ever installed here: `|| exit 0` rather than an error, because a
// destroy must succeed against a machine that failed its install (the common case —
// the resource being destroyed is often the one that did not come up).
func UninstallScript(unit string) string {
	path := lo.If(unit == AgentUnit, "/usr/local/bin/k3s-agent-uninstall.sh").
		Else("/usr/local/bin/k3s-uninstall.sh")
	return strings.Join([]string{
		`set -eu`,
		fmt.Sprintf(`[ -x %[1]s ] || { echo "%[1]s is not present: nothing to uninstall"; exit 0; }`, path),
		fmt.Sprintf(`sudo %s`, path),
		// The marker is in SC's own state dir, which the uninstaller knows nothing
		// about. Left behind it would make the next install's skip condition compare
		// against arguments belonging to a cluster that no longer exists.
		fmt.Sprintf(`sudo rm -f %s`, ArgsMarkerPath(unit)),
		fmt.Sprintf(`echo "uninstalled %s"`, unit),
	}, "\n")
}

// TokenReadScript prints the cluster's join secret, read off a server that is up.
//
// Its stdout is a credential that admits a machine to the control plane, so the
// command built from it carries the same two protections as the kubeconfig read
// (Logging: LoggingNone AND AdditionalSecretOutputs on stdout) — pulumi-command does
// not mark stdout secret, which is how a Yandex service-account key reached a
// world-readable Actions log on 2026-09-30.
//
// The emptiness check is not defensive padding: the file is written asynchronously
// after the server process starts, so a read that wins the race returns success and
// nothing, and the joins built from it then fail one by one as authentication errors
// against a cluster that is perfectly healthy.
func TokenReadScript() string {
	return strings.Join([]string{
		`set -eu`,
		fmt.Sprintf(`test -f %[1]s || { echo "%[1]s does not exist: this host is not a k3s server" >&2; exit 1; }`,
			ServerTokenPath),
		fmt.Sprintf(`TOKEN=$(sudo cat %s)`, ServerTokenPath),
		`[ -n "$TOKEN" ] || { echo "the k3s join token file is empty" >&2; exit 1; }`,
		// No trailing newline: this value is interpolated into another node's install
		// command, and a stray newline there is a token mismatch with no message that
		// says so.
		`printf '%s' "$TOKEN"`,
	}, "\n")
}

// KubeconfigScript prints the admin kubeconfig with its `server:` URL pointed at the
// endpoint the cluster is actually reached on.
//
// The assertions around the rewrite are the point of this function. `sed` reports
// success when it matches nothing, so the straightforward version of this script
// exports a kubeconfig addressed to 127.0.0.1 — which works on the node, works in
// every unit test, and fails only in the child stack's deploy, as a connection
// refused to localhost from a CI runner. Checking both the input and the output turns
// that into a failure here, naming the file (k3s-all-clouds.md §4).
func KubeconfigScript(endpoint string) string {
	wantURL := k3s.KubeconfigURL(endpoint)
	return strings.Join([]string{
		`set -eu`,
		fmt.Sprintf(`test -f %[1]s || { echo "%[1]s does not exist: the k3s server did not start" >&2; exit 1; }`,
			KubeconfigPath),
		fmt.Sprintf(`KC=$(sudo cat %s)`, KubeconfigPath),
		// Only the `server:` line is echoed on failure — the rest of the document is
		// a client certificate and a key.
		fmt.Sprintf(`echo "$KC" | grep -qF %q || { `+
			`echo "unexpected API server URL in the generated kubeconfig: $(echo "$KC" | grep -E '^ *server:')" >&2; `+
			`exit 1; }`, LocalServerURL),
		fmt.Sprintf(`OUT=$(echo "$KC" | sed %q)`, fmt.Sprintf("s|%s|%s|", LocalServerURL, wantURL)),
		fmt.Sprintf(`echo "$OUT" | grep -qF %q || { echo "failed to point the kubeconfig at %s" >&2; exit 1; }`,
			wantURL, wantURL),
		`printf '%s\n' "$OUT"`,
	}, "\n")
}

// NodeReadyScript waits until the cluster's own API says `want` nodes are Ready.
//
// Why this exists next to the install command: `systemctl is-active k3s` is true the
// moment the process starts, seconds before the API server serves and well before the
// node registers. A template that deployed on `is-active` would race the first
// `kubectl apply` against a cluster with no node, which fails as an unschedulable pod
// rather than as a readiness problem — the same class of fault as a deploy that waits
// for SSH and then finds no docker (vm-matrix.md §3.4).
//
// The count is what makes it a FLEET gate rather than a node gate. Without it the
// script passes the instant the first server registers — which on a multi-node
// cluster is before any agent has joined, so a deploy ordered after this gate
// schedules its pods onto a cluster of one machine and the fleet it asked for arrives
// minutes later, if at all. "No node is NotReady" does not catch it either: a node
// that has not registered yet is not NotReady, it is absent.
func NodeReadyScript(want int) string {
	return strings.Join([]string{
		`set -eu`,
		fmt.Sprintf(`WANT=%d`, want),
		fmt.Sprintf(`for i in $(seq 1 %d); do`, nodeReadyAttempts),
		`  STATUS=$(sudo k3s kubectl get nodes --no-headers 2>/dev/null | awk '{print $2}' || true)`,
		// Anchored, so it counts `Ready` and `Ready,SchedulingDisabled` and cannot
		// count `NotReady` — which the unanchored grep below still has to exclude
		// explicitly for the same reason: NotReady CONTAINS Ready.
		`  READY=$(echo "$STATUS" | grep -c '^Ready' || true)`,
		`  if [ -n "$STATUS" ] && ! echo "$STATUS" | grep -q NotReady && [ "$READY" -ge "$WANT" ]; then`,
		`    echo "$READY of $WANT nodes ready"`,
		`    exit 0`,
		`  fi`,
		fmt.Sprintf(`  sleep %d`, nodeReadyInterval),
		`done`,
		fmt.Sprintf(`echo "fewer than $WANT k3s nodes became Ready within %ds" >&2`,
			nodeReadyAttempts*nodeReadyInterval),
		`sudo k3s kubectl get nodes -o wide >&2 || true`,
		fmt.Sprintf(`sudo systemctl status %s --no-pager >&2 || true`, ServerUnit),
		fmt.Sprintf(`sudo journalctl -u %s --no-pager -n 50 >&2 || true`, ServerUnit),
		`exit 1`,
	}, "\n")
}
